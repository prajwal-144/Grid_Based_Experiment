"""Train SISR with direct analytic SIS ray shooting.

Dataset modes:
  controlled: Stage B NPZ files generated by generate_controlled_sis_dataset.py
  legacy:     existing train/<class>/sim_N.npy layout with one fixed theta_E
  manifest:   CSV paths plus per-sample theta_E; this is an SIS approximation
              and is not a final model for elliptical/sheared manifest systems.

The renderer is identical in all modes. Only the dataset adapter and supplied
lens parameters change.
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path
from typing import Dict, Optional

import numpy as np
import torch
import torch.nn.functional as F
from torch.utils.data import DataLoader, Dataset
from tqdm import tqdm

import data
from analytic_sis import AnalyticSISRenderer
from psf import apply_psf, build_psf_kernel
from sisr import SISR

EPS = 1e-8


def normalize_image(array):
    array = np.asarray(array, dtype=np.float32)
    if array.ndim == 2:
        array = array[None]
    if array.ndim != 3:
        raise ValueError(f"Expected CHW or HW image, received {array.shape}")
    minimum, maximum = float(np.nanmin(array)), float(np.nanmax(array))
    if maximum - minimum <= EPS:
        return np.zeros_like(array, dtype=np.float32)
    return ((array - minimum) / (maximum - minimum + EPS)).astype(np.float32)


class ControlledDataset(Dataset):
    def __init__(self, root, split):
        self.files = sorted((Path(root) / split).glob("sample_*.npz"))
        if not self.files:
            raise FileNotFoundError(f"No controlled samples found in {Path(root) / split}")

    def __len__(self):
        return len(self.files)

    def __getitem__(self, index):
        with np.load(self.files[index]) as item:
            return {
                "image": torch.from_numpy(normalize_image(item["lr_image"])),
                "theta_e": torch.tensor(float(item["theta_E"]), dtype=torch.float32),
                "source_truth": torch.from_numpy(np.asarray(item["hr_source"], dtype=np.float32)[None]),
            }


class LegacyDataset(Dataset):
    def __init__(self, directory, classes, count, theta_e):
        self.base = data.LensingDataset(directory, classes, count)
        self.theta_e = float(theta_e)

    def __len__(self):
        return len(self.base)

    def __getitem__(self, index):
        return {
            "image": self.base[index],
            "theta_e": torch.tensor(self.theta_e, dtype=torch.float32),
        }


class ManifestDataset(Dataset):
    """Minimal manifest adapter returning the image and per-system theta_E."""

    def __init__(self, csv_path, data_root, split, limit=None, image_key=None):
        import pandas as pd

        frame = pd.read_csv(csv_path)
        if "path" not in frame or "theta_E" not in frame:
            raise ValueError("Manifest must contain path and theta_E columns")
        if split is not None and "split" in frame:
            frame = frame[frame["split"].astype(str) == str(split)]
        if limit is not None:
            frame = frame.iloc[: int(limit)]
        if frame.empty:
            raise ValueError("Manifest filtering produced no samples")
        self.frame = frame.reset_index(drop=True)
        self.root = Path(data_root)
        self.image_key = image_key

    def __len__(self):
        return len(self.frame)

    def _load_npz(self, path):
        with np.load(path, allow_pickle=True) as item:
            if self.image_key:
                return item[self.image_key]
            candidates = []
            for key in item.files:
                value = np.asarray(item[key])
                if value.ndim in (2, 3) and min(value.shape[-2:]) > 4:
                    candidates.append((value.size, value))
            if not candidates:
                raise ValueError(f"No image-like array found in {path}; pass --npz-image-key")
            return max(candidates, key=lambda entry: entry[0])[1]

    def __getitem__(self, index):
        row = self.frame.iloc[index]
        path = self.root / str(row["path"])
        if not path.exists():
            raise FileNotFoundError(path)
        array = self._load_npz(path) if path.suffix.lower() == ".npz" else np.load(path, allow_pickle=True)
        return {
            "image": torch.from_numpy(normalize_image(array)),
            "theta_e": torch.tensor(float(row["theta_E"]), dtype=torch.float32),
        }


def normalized_wmse(prediction, target, weight):
    weight = weight.to(prediction)
    return (weight * (prediction - target).square()).sum() / weight.sum().clamp_min(EPS)


def arc_weights(image, threshold_fraction, arc_boost, background_weight):
    peak = image.amax(dim=(-2, -1), keepdim=True)
    arc = image >= threshold_fraction * peak.clamp_min(EPS)
    return background_weight + arc.to(image.dtype) * arc_boost


def make_dataset(args, split):
    if args.dataset_mode == "controlled":
        return ControlledDataset(args.controlled_root, split)
    if args.dataset_mode == "legacy":
        count = args.train_count if split == "train" else args.val_count
        return LegacyDataset(f"{split}/", args.classes, count, args.theta_e)
    limit = args.train_count if split == "train" else args.val_count
    return ManifestDataset(
        args.manifest_csv,
        args.manifest_data_root,
        split,
        limit=limit,
        image_key=args.npz_image_key,
    )


def run_epoch(model, loader, optimizer, training, args, forward_renderer, backward_renderer, psf):
    model.train(training)
    totals = {"total": 0.0, "image": 0.0, "source": 0.0, "truth": 0.0, "skill": 0.0}
    batches = 0
    context = torch.enable_grad() if training else torch.no_grad()
    with context:
        for batch in tqdm(loader, desc="train" if training else "val"):
            lr_image = batch["image"].float().to(args.device)
            theta_e = batch["theta_e"].float().to(args.device)
            if lr_image.ndim == 3:
                lr_image = lr_image.unsqueeze(1)
            if lr_image.shape[1] != 1:
                lr_image = lr_image[:, :1]

            source_lr, coverage = backward_renderer.backproject(lr_image, theta_e)
            source_hr = model(torch.cat([source_lr, lr_image], dim=1))
            intrinsic_hr = forward_renderer(source_hr, theta_e)
            convolved_hr = apply_psf(intrinsic_hr, psf)
            pred_lr = F.interpolate(convolved_hr, size=lr_image.shape[-2:], mode="area")
            source_down = F.interpolate(source_hr, size=source_lr.shape[-2:], mode="area")

            image_loss = normalized_wmse(
                pred_lr,
                lr_image,
                arc_weights(lr_image, args.arc_threshold, args.arc_boost, args.background_weight),
            )
            source_loss = normalized_wmse(source_down, source_lr, coverage + 0.05)
            truth_loss = source_hr.new_zeros(())
            if "source_truth" in batch:
                truth = batch["source_truth"].float().to(args.device)
                truth_loss = F.mse_loss(source_hr, truth)
            total = image_loss + args.source_loss_weight * source_loss + args.truth_loss_weight * truth_loss

            if training:
                optimizer.zero_grad(set_to_none=True)
                total.backward()
                torch.nn.utils.clip_grad_norm_(model.parameters(), args.grad_clip)
                optimizer.step()

            raw_mse = F.mse_loss(pred_lr, lr_image)
            zero_mse = lr_image.square().mean().clamp_min(EPS)
            skill = 1.0 - raw_mse / zero_mse
            for name, value in {
                "total": total,
                "image": image_loss,
                "source": source_loss,
                "truth": truth_loss,
                "skill": skill,
            }.items():
                totals[name] += float(value.detach())
            batches += 1
    return {name: value / max(batches, 1) for name, value in totals.items()}


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dataset-mode", choices=["controlled", "legacy", "manifest"], default="controlled")
    parser.add_argument("--controlled-root", default="controlled_sis")
    parser.add_argument("--manifest-csv", default=None)
    parser.add_argument("--manifest-data-root", default=None)
    parser.add_argument("--npz-image-key", default=None)
    parser.add_argument("--classes", nargs="+", default=["no_sub"])
    parser.add_argument("--train-count", type=int, default=2400)
    parser.add_argument("--val-count", type=int, default=800)
    parser.add_argument("--theta-e", type=float, default=3)
    parser.add_argument("--resolution", type=float, required=True, help="LR arcsec/pixel")
    parser.add_argument("--image-shape", type=int, default=64)
    parser.add_argument("--scale-factor", type=int, default=2)
    parser.add_argument("--epochs", type=int, default=100)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--num-workers", type=int, default=0)
    parser.add_argument("--lr", type=float, default=2.5e-4)
    parser.add_argument("--seed", type=int, default=41)
    parser.add_argument("--output-dir", default="outputs_analytic_sis")
    parser.add_argument("--exp-name", default="analytic_sis")
    parser.add_argument("--psf-type", choices=["none", "gaussian", "fits"], default="none")
    parser.add_argument("--psf-path", default=None)
    parser.add_argument("--psf-source-pixscale", type=float, default=None)
    parser.add_argument("--psf-fwhm", type=float, default=0.16)
    parser.add_argument("--source-loss-weight", type=float, default=0.2)
    parser.add_argument("--truth-loss-weight", type=float, default=0.0)
    parser.add_argument("--arc-threshold", type=float, default=0.08)
    parser.add_argument("--arc-boost", type=float, default=20.0)
    parser.add_argument("--background-weight", type=float, default=0.05)
    parser.add_argument("--grad-clip", type=float, default=5.0)
    parser.add_argument("--residual-depth", type=int, default=3)
    parser.add_argument("--latent-space-size", type=int, default=64)
    parser.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    return parser.parse_args()


def main():
    args = parse_args()
    random.seed(args.seed); np.random.seed(args.seed); torch.manual_seed(args.seed)
    device = torch.device(args.device)
    args.device = str(device)
    hr_shape = args.image_shape * args.scale_factor
    hr_scale = args.resolution / args.scale_factor

    forward_renderer = AnalyticSISRenderer(hr_shape, hr_scale, hr_shape, hr_scale).to(device)
    backward_renderer = AnalyticSISRenderer(args.image_shape, args.resolution, args.image_shape, args.resolution).to(device)
    psf = build_psf_kernel(
        psf_type=args.psf_type,
        fwhm_arcsec=args.psf_fwhm,
        pixscale_arcsec=hr_scale,
        path=args.psf_path,
        source_pixscale_arcsec=args.psf_source_pixscale,
        device=device,
    )

    train_loader = DataLoader(make_dataset(args, "train"), batch_size=args.batch_size, shuffle=True, num_workers=args.num_workers)
    val_loader = DataLoader(make_dataset(args, "val"), batch_size=args.batch_size, shuffle=False, num_workers=args.num_workers)
    model = SISR(
        magnification=args.scale_factor,
        n_mag=1,
        residual_depth=args.residual_depth,
        in_channels=2,
        latent_channel_count=args.latent_space_size,
    ).to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=args.lr)

    run_dir = Path(args.output_dir) / args.exp_name
    (run_dir / "checkpoints").mkdir(parents=True, exist_ok=True)
    (run_dir / "args.json").write_text(json.dumps(vars(args), indent=2))
    history = {"train": [], "val": []}
    best = float("inf")
    for epoch in range(args.epochs):
        train_metrics = run_epoch(model, train_loader, optimizer, True, args, forward_renderer, backward_renderer, psf)
        val_metrics = run_epoch(model, val_loader, None, False, args, forward_renderer, backward_renderer, psf)
        history["train"].append(train_metrics); history["val"].append(val_metrics)
        print(f"epoch {epoch + 1}: train={train_metrics} val={val_metrics}")
        checkpoint = {
            "epoch": epoch + 1,
            "model_state_dict": model.state_dict(),
            "optimizer_state_dict": optimizer.state_dict(),
            "args": vars(args),
            "train_metrics": train_metrics,
            "val_metrics": val_metrics,
        }
        torch.save(checkpoint, run_dir / "checkpoints" / "latest.pt")
        if val_metrics["total"] < best:
            best = val_metrics["total"]
            torch.save(checkpoint, run_dir / "checkpoints" / "best.pt")
        (run_dir / "history.json").write_text(json.dumps(history, indent=2))


if __name__ == "__main__":
    main()